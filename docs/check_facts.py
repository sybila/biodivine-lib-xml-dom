#!/usr/bin/env python3
"""Checks the hand-written numbers in the repository documents against the artefacts.

Run from the repository root:

    python3 docs/check_facts.py

A number typed into prose is not a number anything verifies, so every count that a document states
about this repository is checked here:

* the rule summaries in `specification/rules/` against the generated rule coverage table, including
  its per-layer and per-verdict totals;
* the generated `xml_spec::rule_set` module list against the rule files;
* the book's chapter and language-pair counts, by running the book checker;
* the version, single-sourced: the workspace manifest, both crates, and the number the Python test
  asserts.

Anything that is generated (`rule-coverage.md`, `rule_set.rs`) is regenerated by `--check` runs of
its generator in `scripts/verify.sh`, so this script only has to compare the documents with each
other and with the files on disk.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RULES = ROOT / "specification" / "rules"
RULE_SET = ROOT / "src/xml_spec/rule_set.rs"
COVERAGE = ROOT / "docs/design/rule-coverage.md"
BOOK = ROOT / "docs/book"

problems: list[str] = []


def fail(message: str) -> None:
    problems.append(message)


def check_rule_numbers() -> None:
    """The rule files, the generated module list and the coverage table must agree."""
    files = sorted(path.name for path in RULES.glob("rule.*.md"))
    modules = re.findall(r"^pub mod ([a-z0-9_]+) \{\}$", RULE_SET.read_text(encoding="utf-8"), re.M)
    if len(modules) != len(files):
        fail(f"rule_set.rs exposes {len(modules)} modules for {len(files)} rule files")
    expected = [re.sub(r"[.-]", "_", name[: -len(".md")]) for name in files]
    if modules != expected:
        fail("rule_set.rs does not list exactly the rule files, in file order")

    coverage = COVERAGE.read_text(encoding="utf-8")
    rows = len(re.findall(r"^\| `rule\.[^`]+` \|", coverage, re.M))
    if rows != len(files):
        fail(f"rule-coverage.md has {rows} rows for {len(files)} rule files")

    layer_rows = dict(
        re.findall(r"^\| ([A-Z][^|]*?) \| (\d+) \|$", coverage, re.M)
    )
    total = sum(int(count) for count in layer_rows.values())
    if total != len(files):
        fail(f"rule-coverage.md layer counts add up to {total}, not {len(files)}")
    print(f"rule-coverage.md: {rows} rules, layers add up to {total}")

    claimed = re.search(r"Every layer-B, layer-C and layer-D rule carries a verdict: ([^.]*)\.", coverage)
    if not claimed:
        fail("rule-coverage.md does not state the verdict counts")
        return
    stated = {name: int(count) for count, name in re.findall(r"(\d+) ([a-z/]+)", claimed.group(1))}
    counted: dict[str, int] = {}
    for verdict in re.findall(r"^\| `rule\.[^`]+` \| [^|]+ \| ([^|]+?) \|", coverage, re.M):
        key = verdict.split(" (", 1)[0]
        counted[key] = counted.get(key, 0) + 1
    for name, count in stated.items():
        if counted.get(name, 0) != count:
            fail(
                f"rule-coverage.md states {count} {name} rules, the table has {counted.get(name, 0)}"
            )
    print("rule-coverage.md: verdict counts match the table")


def check_book_numbers() -> None:
    """The book's chapter and language-pair counts must match the book itself."""
    result = subprocess.run(
        [sys.executable, str(ROOT / "docs" / "check_book.py")],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        fail(f"docs/check_book.py failed:\n{result.stdout}{result.stderr}")
        return
    chapters = int(re.search(r"(\d+) chapters", result.stdout).group(1))
    pairs = int(re.search(r"(\d+) language pairs", result.stdout).group(1))
    index = (BOOK / "index.md").read_text(encoding="utf-8")
    toctree = index[index.index("```{toctree}") : index.index("```", index.index("```{toctree}") + 3)]
    in_toctree = len(re.findall(r"^\w[\w-]*$", toctree, re.M))
    # The toctree lists every chapter except the index page itself, which check_book.py counts.
    if in_toctree + 1 != chapters:
        fail(f"the book's toctree lists {in_toctree} chapters plus the index, check_book.py counts {chapters}")
    print(f"book: {chapters} chapters, {pairs} language pairs (verified against the book itself)")


def check_document_list() -> None:
    """The documents the `documentation` module includes must all exist and be listed in the book."""
    module = (ROOT / "src/documentation.rs").read_text(encoding="utf-8")
    included = set(re.findall(r'include_str!\("\.\./docs/design/([a-z-]+\.md)"\)', module))
    if not included:
        fail("the documentation module includes no documents")
    # The Rust filesystem may be case-insensitive, so compare names without their case.
    on_disk = {path.name.lower() for path in (ROOT / "docs/design").glob("*.md")}
    unlisted = sorted(included - on_disk)
    if unlisted:
        fail(f"documentation.rs includes documents that do not exist: {unlisted}")
    orphaned = sorted(on_disk - included)
    if orphaned:
        fail(f"docs/design contains documents that documentation.rs does not include: {orphaned}")
    notes = (BOOK / "design-notes.md").read_text(encoding="utf-8")
    missing = sorted(
        name
        for name in included
        if f"documentation::{name[:-3].replace('-', '_')}" not in notes
    )
    if missing:
        fail(f"the book's design-notes chapter does not point at {missing}")
    print(f"documentation module: {len(included)} documents, all present and referenced by the book")


def check_display_name() -> None:
    """The public-facing documents present the library under its display name."""
    name = "Biodivine XML DOM"
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    if f"# {name}" not in readme:
        fail(f"README.md does not start with the display name `{name}`")
    index = (BOOK / "index.md").read_text(encoding="utf-8")
    if f"# {name}" not in index:
        fail(f"the book index does not start with the display name `{name}`")
    theme = (BOOK / "conf.py").read_text(encoding="utf-8")
    if f'html_title = "{name}"' not in theme:
        fail(f"the book's html_title is not `{name}`")
    print(f"display name: `{name}` in the README, the book and its page title")


def check_version() -> None:
    """One version number, in the manifest, both crates and the Python surface test."""
    manifest = (ROOT / "Cargo.toml").read_text(encoding="utf-8")
    workspace_version = re.search(r'^version = "([^"]+)"', manifest, re.M).group(1)
    for crate in (ROOT / "Cargo.toml", ROOT / "biodivine-lib-xml-dom-py-sys/Cargo.toml"):
        if "version.workspace = true" not in crate.read_text(encoding="utf-8"):
            fail(f"{crate} does not inherit the workspace version")
    test = (ROOT / "biodivine-lib-xml-dom-py-sys/tests-python/test_public_surface.py").read_text(
        encoding="utf-8"
    )
    if f'"{workspace_version}"' not in test:
        fail(f"the public-surface test does not assert the workspace version {workspace_version}")
    pyproject = (ROOT / "biodivine-lib-xml-dom-py-sys/pyproject.toml").read_text(encoding="utf-8")
    if 'dynamic = ["version"]' not in pyproject:
        fail("pyproject.toml does not take its version from the manifest")
    print(f"version: {workspace_version}, inherited by both crates, asserted from Python")


def main() -> int:
    for check in (
        check_rule_numbers,
        check_book_numbers,
        check_document_list,
        check_display_name,
        check_version,
    ):
        check()
    if problems:
        print(f"\n{len(problems)} fact problem(s):", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1
    print("every stated number matches the artefact")
    return 0


if __name__ == "__main__":
    sys.exit(main())
