#!/usr/bin/env python3
"""Generates `src/xml_spec/rule_set.rs` from the rule summaries in `specification/rules/`.

Run from the repository root:

    python3 scripts/gen_rule_set.py            # write src/xml_spec/rule_set.rs
    python3 scripts/gen_rule_set.py --check    # fail if the file is out of date

Every rule summary in `specification/rules/` becomes one module of `xml_spec::rule_set`, documented
with the summary itself::

    #[doc = include_str!("../../specification/rules/rule.well-formedness.comment-no-double-hyphen.md")]
    pub mod rule_well_formedness_comment_no_double_hyphen {}

That keeps two properties at once:

* the markdown files stay the single source of truth — nothing here paraphrases them, and the
  generated file contains no rule text of its own;
* the documentation of this crate can link to a rule instead of naming a file, so a reader of the
  API reference can see the specification text behind a check without leaving the documentation.

The module name is the file name with the `.md` suffix removed and `.`/`-` replaced by `_`; the
mapping is checked for collisions and for valid identifiers before anything is written.

`--check` exists for continuous verification: it regenerates the file in memory and compares, so a
rule summary that is added, renamed or deleted cannot silently desynchronize the documentation.
"""

import argparse
import difflib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RULES = ROOT / "specification" / "rules"
TARGET = ROOT / "src" / "xml_spec" / "rule_set.rs"

#: Rust keywords, plus the identifiers that a module name must not become.
RESERVED = {
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
    "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try",
}

HEADER = """// Generated by `scripts/gen_rule_set.py`; do not edit by hand.
//!
//! The XML specification rules, one module per rule summary in `specification/rules/`.
//!
//! Every module below is documented with the contents of its summary file, so the markdown in
//! `specification/rules/` remains the single source of truth and a code path that enforces a rule
//! can link to the module instead of naming a file. The module name is the file name without the
//! `.md` suffix, with `.` and `-` replaced by `_`: `rule.attributes.id-must-be-unique` becomes
//! [`rule_attributes_id_must_be_unique`].
//!
//! The summaries describe the specification, not the implementation: some of them are rules this
//! library enforces, and some describe behaviour it deliberately leaves to the caller or cannot
//! support without DTD processing. Which is which is recorded in the rule coverage list, which is
//! part of the development documentation (`documentation::rule_coverage`).
//!
//! The summaries quote the specification's own notation — `[VC]`, `[WFC: ...]`, `[3]`, and bare
//! URLs — which rustdoc would otherwise report as unresolved links and bare URLs. They are rendered
//! as written, so those two lints are switched off for this module and its children only.
#![allow(rustdoc::broken_intra_doc_links, rustdoc::bare_urls)]
"""


def module_name(file_name: str) -> str:
    """Maps a rule summary file name to the name of its module."""
    stem = file_name[: -len(".md")]
    return re.sub(r"[.-]", "_", stem)


def rule_modules() -> list[tuple[str, str]]:
    """Every rule summary as `(file name, module name)`, sorted by file name."""
    files = sorted(path.name for path in RULES.glob("rule.*.md"))
    if not files:
        sys.exit(f"no rule summaries found in {RULES}")

    modules = [(name, module_name(name)) for name in files]
    seen: dict[str, str] = {}
    for file_name, module in modules:
        if not re.fullmatch(r"[a-z][a-z0-9_]*", module):
            sys.exit(f"{file_name} maps to the invalid module name {module!r}")
        if module in RESERVED:
            sys.exit(f"{file_name} maps to the reserved word {module!r}")
        if module in seen:
            sys.exit(f"{file_name} and {seen[module]} both map to {module!r}")
        seen[module] = file_name
    return modules


def render(modules: list[tuple[str, str]]) -> str:
    """Renders the whole generated file."""
    lines = [HEADER]
    for file_name, module in modules:
        lines.append(
            f'\n#[doc = include_str!("../../specification/rules/{file_name}")]\npub mod {module} {{}}\n'
        )
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write anything; fail if src/xml_spec/rule_set.rs is out of date",
    )
    arguments = parser.parse_args()

    modules = rule_modules()
    generated = render(modules)

    if arguments.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != generated:
            print(
                f"{TARGET.relative_to(ROOT)} is out of date: run scripts/gen_rule_set.py",
                file=sys.stderr,
            )
            diff = difflib.unified_diff(
                current.splitlines(), generated.splitlines(), "on disk", "generated", lineterm=""
            )
            for line in list(diff)[:40]:
                print(line, file=sys.stderr)
            return 1
        print(f"{TARGET.relative_to(ROOT)}: {len(modules)} rule modules (up to date)")
        return 0

    TARGET.write_text(generated, encoding="utf-8")
    print(f"{TARGET.relative_to(ROOT)}: {len(modules)} rule modules written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
